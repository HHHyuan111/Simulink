function frame=pmsm_vector_frame(data,caseIndex,windowIndex,requestedTime)
% Snap a cursor to retained native samples; never interpolate or shift phases.
validateattributes(caseIndex,{'double'},{'scalar','integer','>=',1,'<=',numel(data.cases)});
validateattributes(windowIndex,{'double'},{'scalar','integer','>=',1,'<=',numel(data.windows)});
c=data.cases(caseIndex);w=data.windows(windowIndex);
if nargin<4,requestedTime=w.bounds_s(2);end
validateattributes(requestedTime,{'double'},{'scalar','real','finite'});
request=min(w.bounds_s(2),max(w.bounds_s(1),requestedTime));
[~,local]=min(abs(c.time_s(w.indices)-request));idx=w.indices(local);
frame=struct('case_index',caseIndex,'window_index',windowIndex,'window_name',w.name, ...
 'bounds_s',w.bounds_s,'index',idx,'time_s',c.time_s(idx),'indices',w.indices, ...
 'history_indices',w.indices(w.indices<=idx),'limits',w.limits,'abc_A',c.abc_A(idx,:), ...
 'alpha_beta_A',c.alpha_beta_A(idx,:),'dq_true_A',c.dq_true_A(idx,:), ...
 'dq_feedback_A',c.dq_feedback_A(idx,:),'dq_reference_A',c.dq_reference_A(idx,:), ...
 'theta_true_rad',c.theta_true_rad(idx),'theta_control_rad',c.theta_control_rad(idx), ...
 'angle_error_deg',c.angle_error_deg(idx));
end
