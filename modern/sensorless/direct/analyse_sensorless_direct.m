function m=analyse_sensorless_direct(s,c)
% Evaluate every sample in the fixed normal-convergence window.
names=fieldnames(s);finite=true;endpoint=false;
for k=1:numel(names)
 q=s.(names{k});finite=finite&&all(isfinite(q.Time),'all')&&all(isfinite(q.Data),'all')&&all(diff(q.Time)>=0);
 endpoint=endpoint||abs(q.Time(end)-c.duration_s)<1e-12;
end
t=s.obs_sless_v2_theta.Time;theta=teach_values(s.obs_sless_v2_theta);truth=teach_values(s.obs_sless_v2_truth_theta);
speed=teach_values(s.obs_sless_v2_speed);actual=teach_values(s.obs_sless_v2_truth_speed);
angle=atan2(sin(theta-truth),cos(theta-truth))*180/pi;error=speed-actual;
use=t>=c.steady_window_s(1)-1e-12&t<=c.steady_window_s(2)+1e-12;
x=t(use);y=actual(use);slope=sum((x-mean(x)).*(y-mean(y)))/sum((x-mean(x)).^2);
u=unwrap(truth(use));cycles=abs(u(end)-u(1))/(2*pi);
p=teach_values(s.obs_sless_direct_completed);pt=s.obs_sless_direct_completed.Time;
permit=p(:,14)>.5;
pu=p(:,2)>=c.steady_window_s(1)-1e-12&p(:,2)<=c.steady_window_s(2)+1e-12;
m=struct('window_s',c.steady_window_s,'angle_rms_deg',sqrt(mean(angle(use).^2)),...
 'angle_peak_deg',max(abs(angle(use))),'speed_mean_relative',abs(mean(error(use)))/abs(c.speed_rpm),...
 'speed_rms_relative',sqrt(mean(error(use).^2))/abs(c.speed_rpm),'plant_mean_rpm',mean(y),...
 'plant_slope_rpm_s',slope,'electrical_cycles',cycles,'completed_permit_fraction',mean(permit(pu)),...
 'samples',numel(t),'completed_packets',size(p,1));
m.checks=struct('finite',finite,'endpoint',endpoint,'sample_count',numel(t)==c.observer_samples,...
 'cycles',cycles>=c.minimum_electrical_cycles,'angle_rms',m.angle_rms_deg<=c.angle_rms_deg_max,...
 'angle_peak',m.angle_peak_deg<=c.angle_peak_deg_max,'speed_mean',m.speed_mean_relative<=c.speed_mean_relative_max,...
 'speed_rms',m.speed_rms_relative<=c.speed_rms_relative_max,...
 'plant_mean',abs(m.plant_mean_rpm-c.speed_rpm)/abs(c.speed_rpm)<=c.plant_target_relative_max,...
 'plant_slope',abs(slope)<=c.plant_slope_rpm_s_max,...
 'permit',m.completed_permit_fraction>=c.completed_permit_fraction_min,...
 'publication_count',size(p,1)==c.observer_samples,...
 'publication_sequence',isequal(p(:,1),(0:c.observer_samples-1)'),...
 'publication_reference',max(abs(p(:,2)-t))<=1e-12,...
 'publication_delay',max(abs(p(:,3)-p(:,2)-c.publication_delay_s))<=1e-12,...
 'publication_time',max(abs(pt-p(:,3)))<=1e-12,...
 'denied_zero',all(p(~permit,9:11)==0,'all'));
m.passed=all(structfun(@(v)v,m.checks));
end
