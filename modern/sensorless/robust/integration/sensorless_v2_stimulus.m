function backup=sensorless_v2_stimulus(mdl,testcase)
% All physical changes are local in-memory Mask settings. Original code kept.
basic=struct('speed_rpm',3000,'configuration',struct('bridge','same_detailed_freewheel','gate_deadtime_us',.5));
backup=sensorless_n3_stimulus(mdl,basic);
here=fileparts(mfilename('fullpath'));p=jsondecode(fileread(fullfile(fileparts(fileparts(here)),'contracts','nonideal_v2.json')));
i=p.engineering_profile.plant_injection;
settle_us=.5;if isfield(testcase,'window_settle_s'),settle_us=testcase.window_settle_s*1e6;end
set_param([mdl '/时序设置'],'real_on','on','window_on',switch_text(testcase.window_on),...
 'trigger_us','24.375','compute_us',num2str(8+testcase.interference_s*1e6,17),'sync_us','0',...
 'settle_us',num2str(settle_us,17),'grid_divider','1','pwm_on','off');
set_param([mdl '/功率设置'],'gate_on','on','gate_us',num2str(i.deadtime_s*1e6,17),...
 'drop_on','on','ron',num2str(i.Ron_ohm,17),'vf',num2str(i.Vf_V,17),...
 'zero_A',num2str(i.zero_current_band_A,17),'comp_on','off','dead_on','off');
set_param([mdl '/采样设置'],'gain_on','on','phase_gain',mat2str(i.gain_ABC(:),17),...
 'bias_on','on','bias_A',mat2str(i.bias_ABC_A(:),17),'noise_on','on',...
 'noise_rms',num2str(i.noise_rms_A,17),'noise_seed',num2str(i.noise_seed),...
 'adc_on','on','adc_bits',num2str(i.adc_bits),'adc_span',num2str(testcase.adc_span_A,17),...
 'analog_on','on','analog_hz',num2str(i.analog_filter_hz,17),...
 'filter_on','on','filter_hz',num2str(i.digital_filter_hz,17),'delay_on','off');
end
function s=switch_text(value)
s='off';if value,s='on';end
end
