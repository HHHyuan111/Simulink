function m=analyse_sensorless_closed(s,c)
base=fileparts(fileparts(mfilename('fullpath')));addpath(fullfile(fileparts(base),'teaching'));
t=s.obs_closed_theta_sample.Time;theta=teach_values(s.obs_closed_theta_sample);truth=teach_values(s.obs_sless_v2_truth_theta);
rawTheta=teach_values(s.obs_sless_v2_theta);speed=teach_values(s.obs_sless_v2_truth_speed);estimate=teach_values(s.obs_closed_speed);
stage=teach_values(s.obs_closed_stage);blend=teach_values(s.obs_closed_blend);age=teach_values(s.obs_closed_age);
use=t>=c.steady_window_s(1)-1e-12&t<=c.steady_window_s(2)+1e-12;
error=atan2(sin(theta-truth),cos(theta-truth))*180/pi;rawError=atan2(sin(rawTheta-truth),cos(rawTheta-truth))*180/pi;
e=speed-c.target_rpm;de=estimate-speed;unwrapped=unwrap(truth(use));cycles=abs(unwrapped(end)-unwrapped(1));
first=find(stage==5,1);closedTime=NaN;if ~isempty(first),closedTime=t(first);end
current=teach_values(s.log_iabc_true);
m=struct('takeover_complete_s',closedTime,'steady_window_s',c.steady_window_s,...
 'speed_target_mean_relative',abs(mean(e(use)))/c.target_rpm,'speed_target_rms_relative',sqrt(mean(e(use).^2))/c.target_rpm,...
 'observer_speed_rms_relative',sqrt(mean(de(use).^2))/c.target_rpm,...
 'observer_angle_rms_deg',sqrt(mean(rawError(use).^2)),'observer_angle_peak_deg',max(abs(rawError(use))),...
 'control_angle_rms_deg',sqrt(mean(error(use).^2)),'control_angle_peak_deg',max(abs(error(use))),...
 'phase_current_peak_A',max(abs(current),[],'all'),'speed_peak_rpm',max(speed),...
 'electrical_cycles',cycles/(2*pi),'steady_feedback_fresh_fraction',mean(age(use)<=1e-12),...
 'steady_stage',unique(stage(use))','stage_sequence',unique(stage,'stable')');
finite=true;for name=fieldnames(s)',v=s.(name{1});finite=finite&&all(isfinite(v.Time),'all')&&all(isfinite(v.Data),'all');end
m.checks=struct('finite',finite,'observations',numel(t)==round(c.duration_s/50e-6),...
 'takeover',isfinite(closedTime)&&closedTime<=c.takeover_complete_by_s,'closed_retained',all(stage(use)==5)&&all(blend(use)==1),...
 'target_mean',m.speed_target_mean_relative<=c.steady_speed_target_mean_relative_max,...
 'target_rms',m.speed_target_rms_relative<=c.steady_speed_target_rms_relative_max,...
 'observer_speed',m.observer_speed_rms_relative<=c.steady_observer_speed_rms_relative_max,...
 'observer_angle_rms',m.observer_angle_rms_deg<=c.steady_observer_angle_rms_deg_max,...
 'observer_angle_peak',m.observer_angle_peak_deg<=c.steady_observer_angle_peak_deg_max,...
 'control_angle_rms',m.control_angle_rms_deg<=c.steady_control_angle_rms_deg_max,...
 'control_angle_peak',m.control_angle_peak_deg<=c.steady_control_angle_peak_deg_max,...
 'current_peak',m.phase_current_peak_A<=c.phase_current_peak_A_max,...
 'overshoot',m.speed_peak_rpm<=c.target_rpm*(1+c.speed_overshoot_relative_max),...
 'cycles',m.electrical_cycles>=c.minimum_electrical_cycles,...
 'estimate_available',m.steady_feedback_fresh_fraction>=c.steady_permit_fraction_min);
m.passed=all(structfun(@(v)v,m.checks));
end
