function export_sensorless_robust_r0(first,second)
% Read-only review export. Scientific acceptance remains the original MAT.
here=fileparts(mfilename('fullpath'));addpath(fullfile(fileparts(here),'teaching'));
out=fullfile(here,'milestones','N3R0');if ~isfolder(out),mkdir(out);end
a=jsondecode(fileread(fullfile(first,'record.json')));b=jsondecode(fileread(fullfile(second,'record.json')));
replay=jsondecode(fileread(fullfile(second,'replay_validation.json')));assert(a.all_passed&&b.all_passed&&replay.all_passed);
assert(strcmp(a.raw_sha256,teach_hash(fullfile(first,'raw.mat'))));r=load(fullfile(first,'raw.mat'));raw=r.raw;
files={fullfile(first,'record.json'),'first_record.json';fullfile(second,'record.json'),'replay_record.json';...
 fullfile(first,'metrics.json'),'component_metrics.json';fullfile(first,'effective_parameters.json'),'effective_parameters.json';...
 fullfile(second,'replay_validation.json'),'replay_validation.json';fullfile(first,'launcher_record.json'),'first_launcher.json';...
 fullfile(second,'launcher_record.json'),'replay_launcher.json'};
for k=1:size(files,1),copyfile(files{k,1},fullfile(out,files{k,2}));end
campaign=fullfile(fileparts(first),'campaign.json');
if isfile(campaign)&&strcmp(fileparts(first),fileparts(second)),copyfile(campaign,fullfile(out,'campaign.json'));end
names={'bus_V','Ron_hat_ohm','Vf_hat_V','gate_AH','gate_AL','gate_BH','gate_BL','gate_CH','gate_CL',...
 'iA_A','iB_A','iC_A','emfA_V','emfB_V','emfC_V','estimated_alpha_V','estimated_beta_V',...
 'estimated_A_V','estimated_B_V','estimated_C_V','oracle_A_V','oracle_B_V','oracle_C_V',...
 'path_A','path_B','path_C','ambiguous_A','ambiguous_B','ambiguous_C','voltage_confident','oracle_solutions','error_V','passed'};
writetable(array2table(raw.bridge,'VariableNames',names),fullfile(out,'bridge_cases.csv'));
names={'requested_deadtime_us','effective_deadtime_ticks','tick','request_AH','request_AL','request_BH','request_BL','request_CH','request_CL',...
 'gate_AH','gate_AL','gate_BH','gate_BL','gate_CH','gate_CL','oracle_AH','oracle_AL','oracle_BH','oracle_BL','oracle_CH','oracle_CL','blank_A','blank_B','blank_C'};
t=array2table(raw.deadtime,'VariableNames',names);c=jsondecode(fileread(fullfile(first,'effective_parameters.json')));
t.time_us=t.tick*c.h_s*1e6;t.effective_deadtime_us=t.effective_deadtime_ticks*c.h_s*1e6;writetable(t,fullfile(out,'deadtime_edges.csv'));
names={'cycle','update_mode','release_jitter_us','interference_us','guard_us','adc_A_s','adc_B_s','adc_C_s','reference_s',...
 'task_release_s','observer_available_s','ccr_write_s','intended_pwm_apply_s','actual_pwm_apply_s','deadline_s',...
 'reserved_slack_s','missed_update','next_frame_overrun','speed_task_active','timing_valid','oracle_timing_valid','passed'};
writetable(array2table(raw.schedule,'VariableNames',names),fullfile(out,'event_schedule.csv'));
rows=struct([]);
for k=1:numel(raw.publication)
 x=raw.publication(k);v=x.output;
 q=struct('case_id',x.name,'query_time_s',x.now_s,'pwm_apply_s',x.pwm_apply_s,'sequence',v.sequence,...
  'live_input_valid',x.live_input_valid,'live_timing_valid',x.live_timing_valid,...
  'reference_s',v.reference_time_s,'available_s',v.available_time_s,'age_s',v.age_s,...
  'theta_sample_rad',v.theta_sample_rad,'theta_now_rad',v.theta_now_rad,'theta_pwm_rad',v.theta_pwm_rad,...
  'raw_speed_rpm',v.raw_speed_rpm,'control_theta_sample_rad',v.control_theta_sample_rad,...
  'control_theta_pwm_rad',v.control_theta_pwm_rad,'control_speed_rpm',v.control_speed_rpm,...
  'control_permit',v.control_permit,'reason',double(v.reason),'expected_reason',x.expected_reason,'passed',x.passed);
 if isempty(rows),rows=q;else,rows(end+1)=q;end %#ok<AGROW>
end
writetable(struct2table(rows),fullfile(out,'publication_cases.csv'));
sources=struct('path',{},'sha256',{});
for name={'bridge_cases.csv','deadtime_edges.csv','event_schedule.csv','publication_cases.csv'}
 sources(end+1)=struct('path',name{1},'sha256',teach_hash(fullfile(out,name{1})));
end
teach_writejson(fullfile(out,'figure_provenance.json'),struct('node','N3R0','first_folder',first,'second_folder',second,...
 'raw_sha256_first',a.raw_sha256,'raw_sha256_second',b.raw_sha256,'science_decimation',false,...
 'csv_sources',sources,'exporter_sha256',teach_hash([mfilename('fullpath') '.m'])));
teach_writejson(fullfile(out,'summary.json'),struct('node','N3R0','status','component_passed_awaiting_user_review',...
 'component_checks_passed',true,'complete_replay_identical',true,'raw_numeric_elements',a.raw_numeric_elements,...
 'main_model_integrated',false,'nonideal_integrated_performance_passed',false,'hardware_validated',false,...
 'historical_N3_all_passed',false,'original_model_sha256',a.model_sha256));
end
